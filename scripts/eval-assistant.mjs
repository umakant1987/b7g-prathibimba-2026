// Runs evals/question-bank.json through the offline AI assistant and reports
// pass/fail. `npm run eval:ai -- --write` also regenerates
// docs/AI_QUESTION_BANK.md from the results.
import { readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const write = process.argv.includes('--write');
const bank = JSON.parse(readFileSync(new URL('../evals/question-bank.json', import.meta.url), 'utf8'));

// The question bank tests the offline assistant; never call the backend RAG from here.
process.env.VITE_RAG_API_URL = '';
// Test the full assistant, as it will be once the detailed programme is released.
process.env.VITE_SHOW_PROGRAMME_DETAILS = 'true';
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const { answerQuestion } = await server.ssrLoadModule('/src/services/ai/ragService.ts');

const DECLINE = /don't have|limited information|haven't been|not yet|ಇನ್ನೂ ಇಲ್ಲ|couldn't find/i;

function check(result, expect = {}) {
  const problems = [];
  const text = result.answer.toLowerCase();
  const cards = (result.cards ?? []).map((c) => c.id);
  if (expect.cards) {
    const want = [...expect.cards].sort().join(',');
    if (cards.sort().join(',') !== want) problems.push(`cards [${cards.join(', ')}] ≠ [${expect.cards.join(', ')}]`);
  }
  for (const s of expect.includes ?? []) if (!text.includes(s.toLowerCase())) problems.push(`missing "${s}"`);
  for (const s of expect.excludes ?? []) if (text.includes(s.toLowerCase())) problems.push(`contains "${s}"`);
  if (expect.declines && result.grounded && !DECLINE.test(result.answer)) problems.push('should decline');
  return problems;
}

let passed = 0;
let failed = 0;
let llmOnly = 0;
const report = [];

for (const category of bank.categories) {
  const rows = [];
  for (const c of category.cases) {
    const lang = c.lang ?? 'en';
    if (c.mode === 'llm') {
      llmOnly += 1;
      rows.push({ c, status: '🤖', note: 'Needs a real model' });
      continue;
    }
    let context = {};
    if (c.after) {
      const first = await answerQuestion(c.after, lang, context);
      context = { lastGuestId: first.guestId };
    }
    const result = await answerQuestion(c.q, lang, context);
    const problems = check(result, c.expect);
    if (problems.length === 0) passed += 1;
    else failed += 1;
    rows.push({ c, status: problems.length ? '❌' : '✅', note: problems.join('; '), result });
    if (problems.length) {
      console.log(`❌ [${category.name}] ${c.after ? `(after "${c.after}") ` : ''}${c.q}\n   ${problems.join('; ')}\n   got: ${result.answer.replace(/\n/g, ' ⏎ ').slice(0, 160)}`);
    }
  }
  report.push({ category, rows });
}

await server.close();
console.log(`\n${passed} passed, ${failed} failed, ${llmOnly} need a real model (not run).`);

if (write) {
  const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const lines = [
    '# AI Assistant Question Bank',
    '',
    '> Generated by `npm run eval:ai -- --write` from [evals/question-bank.json](../evals/question-bank.json). Edit the JSON, not this file.',
    '',
    `**${passed} passing · ${failed} failing · ${llmOnly} need a real model** (offline assistant, without the backend RAG).`,
    '',
    'Legend: ✅ answered correctly offline · ❌ wrong offline · 🤖 needs a real model (LLM) — not checked offline.',
    '',
    '## How questions are routed',
    '',
    '| Question type | Answered from | File |',
    '|---|---|---|',
    '| Name only / "Who is X?" | Guest profile card (frontmatter + Summary) | `knowledge/chief-guests/*.md` |',
    '| "Who are the guests?" | Guest cards with exact role and date | `knowledge/chief-guests/*.md` |',
    '| Specific guest question, incl. "he/his" follow-ups | The matching `##` section of that guest\'s file | `knowledge/chief-guests/*.md` |',
    '| Now / next / at 6 pm / kids / full schedule | Structured schedule | `src/data/programs.ts` |',
    '| Sponsors | Structured sponsor list | `src/data/sponsors.ts` |',
    '| Everything else | Best-matching knowledge section | `knowledge/*.md` (+ Kannada entries in `src/data/knowledgeBase.ts`) |',
    '| Nothing matches | Honest "I don\'t have that information…" | — |',
    '',
    'Tip for adding knowledge: write `##` headings as the question people will ask (e.g. "What movies has he acted in?"), keep each section self-contained (name the person), and add a section for known unknowns (e.g. "What books has he written?" → titles not yet added) so the assistant declines precisely instead of guessing.',
    '',
  ];
  for (const { category, rows } of report) {
    lines.push(`## ${category.name}`, '', category.purpose, '', '| | Question | Expected behaviour | Offline answer |', '|---|---|---|---|');
    for (const { c, status, note, result } of rows) {
      const q = `${c.after ? `*(after "${esc(c.after)}")* ` : ''}${esc(c.q)}${c.lang === 'kn' ? ' *(kn)*' : ''}`;
      const got = result
        ? `${result.cards?.length ? `[cards: ${result.cards.map((x) => x.name).join(', ')}] ` : ''}${esc(result.answer.slice(0, 110))}${result.answer.length > 110 ? '…' : ''}`
        : '';
      lines.push(`| ${status} | ${q} | ${esc(c.behaviour)}${note && status === '❌' ? ` — **${esc(note)}**` : ''} | ${got} |`);
    }
    lines.push('');
  }
  writeFileSync(new URL('../docs/AI_QUESTION_BANK.md', import.meta.url), `${lines.join('\n')}\n`);
  console.log('Wrote docs/AI_QUESTION_BANK.md');
}

process.exit(failed > 0 ? 1 : 0);
